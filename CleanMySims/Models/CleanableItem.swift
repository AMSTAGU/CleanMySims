import Foundation

nonisolated enum Platform: String, CaseIterable, Sendable {
    case xcode = "Xcode"
    case android = "Android"
}

nonisolated enum CleanableItemType: String, CaseIterable, Sendable {
    // Xcode (sidebar order)
    case testClones = "Test Clones"
    case runtimes = "Runtimes"
    case builds = "Builds"
    case deviceSupport = "Device Support"
    case previews = "Previews"
    case cache = "Caches"
    case archives = "Archives"
    case virtualDevice = "Simulators"
    // Android
    case androidSdk = "Android SDK"
    case androidEmulator = "Android Emulators"
    case gradleCache = "Gradle"
    case androidStudioCache = "Android Studio"

    var title: String { rawValue }

    /// Shorter label used in the sidebar, where the section already says "Android".
    var shortTitle: String {
        switch self {
        case .androidSdk: return "SDK"
        case .androidEmulator: return "Emulators"
        default: return rawValue
        }
    }

    var platform: Platform {
        switch self {
        case .androidSdk, .androidEmulator, .gradleCache, .androidStudioCache: return .android
        default: return .xcode
        }
    }

    /// Data the tools recreate on demand: deleting it never loses work.
    var isSafeToDelete: Bool {
        switch self {
        case .testClones, .previews, .cache, .builds, .gradleCache, .androidStudioCache: return true
        default: return false
        }
    }

    var iconName: String {
        switch self {
        case .testClones: return "rectangle.portrait.on.rectangle.portrait.fill"
        case .runtimes: return "square.stack.3d.up.fill"
        case .builds: return "hammer.fill"
        case .deviceSupport: return "cable.connector"
        case .previews: return "eye.fill"
        case .cache: return "archivebox.fill"
        case .archives: return "shippingbox.fill"
        case .virtualDevice: return "iphone"
        case .androidSdk: return "cpu.fill"
        case .androidEmulator: return "candybarphone"
        case .gradleCache: return "cube.fill"
        case .androidStudioCache: return "wrench.and.screwdriver.fill"
        }
    }

    var helpText: String {
        switch self {
        case .testClones: return "Simulator clones created by Xcode for parallel testing (XCTestDevices). Recreated when needed."
        case .runtimes: return "Simulator OS versions. Delete the ones you no longer test on."
        case .builds: return "Compilation data generated by Xcode (DerivedData). Rebuilt on the next build."
        case .deviceSupport: return "Symbols for the physical devices you plugged in. Re-copied when the device is connected again."
        case .previews: return "Simulators used by SwiftUI previews. Recreated when needed."
        case .cache: return "Simulator caches: logs, dyld caches, downloaded data."
        case .archives: return "App archives from Product > Archive. They hold the dSYMs needed to symbolicate crash reports."
        case .virtualDevice: return "Simulators listed in Xcode. Their apps and data are lost when deleted."
        case .androidSdk: return "SDK platforms, build tools and system images."
        case .androidEmulator: return "Android virtual devices (~/.android/avd)."
        case .gradleCache: return "Gradle build caches and wrapper distributions. Downloaded again when needed."
        case .androidStudioCache: return "Android Studio caches and indexes. Rebuilt on launch."
        }
    }

    /// How items of this category are removed, as told in confirmations.
    var removalNote: String {
        switch self {
        case .virtualDevice, .testClones, .previews: return "Deleted with simctl."
        case .runtimes: return "Removed with simctl runtime delete."
        case .cache: return "Deleted permanently (system caches through simctl). Recreated when needed."
        case .builds, .gradleCache, .androidStudioCache: return "Deleted permanently. Recreated when needed."
        case .androidEmulator: return "Deleted with avdmanager."
        case .androidSdk: return "Uninstalled with sdkmanager."
        case .deviceSupport, .archives: return "Moved to the Trash."
        }
    }

    static func types(for platform: Platform) -> [CleanableItemType] {
        allCases.filter { $0.platform == platform }
    }
}

/// Classifies DerivedData entries into logical groups for the Builds tab.
nonisolated enum BuildGroup: String, CaseIterable, Comparable, Sendable {
    case apps = "Apps"
    case runners = "Flutter / Runners"
    case xcodeCache = "Xcode Caches"

    var icon: String {
        switch self {
        case .apps: return "app.fill"
        case .runners: return "arrow.triangle.2.circlepath"
        case .xcodeCache: return "memorychip"
        }
    }

    private var sortOrder: Int {
        switch self {
        case .apps: return 0
        case .runners: return 1
        case .xcodeCache: return 2
        }
    }

    static func < (lhs: BuildGroup, rhs: BuildGroup) -> Bool {
        lhs.sortOrder < rhs.sortOrder
    }

    /// Classifies a DerivedData folder name into a group.
    static func classify(folderName: String) -> BuildGroup {
        // Caches: names ending in .noindex
        if folderName.hasSuffix(".noindex") {
            return .xcodeCache
        }
        // Runners: Flutter/React Native projects
        let baseName = folderName.components(separatedBy: "-").first ?? folderName
        if baseName == "Runner" {
            return .runners
        }
        return .apps
    }
}

nonisolated struct CleanableItem: Identifiable, Hashable, Sendable {
    /// Unique id. For simulators it is the device UDID, for simctl runtimes the runtime identifier.
    let id: String
    let name: String
    let path: String
    let size: Int64
    let type: CleanableItemType
    let details: String?
    var appIconPath: String? = nil
    var buildGroup: BuildGroup? = nil

    var sizeString: String {
        size.formatted(.byteCount(style: .file))
    }
}
