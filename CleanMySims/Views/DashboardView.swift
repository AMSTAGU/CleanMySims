import SwiftUI

struct DashboardView: View {
    @EnvironmentObject var simulatorManager: SimulatorManager
    @State private var showScanComplete = false
    @State private var showCleanComplete = false

    private let iosCategories: [(type: CleanableItemType, title: String, help: String)] = [
        (.cache, "Caches", "Temporary simulator data: logs, compilation caches, downloaded data"),
        (.virtualDevice, "Simulators", "Virtual iOS devices used by Xcode to test your apps"),
        (.runtimes, "Runtimes", "iOS versions installed to run the simulators"),
        (.builds, "Builds", "Compilation data generated by Xcode (DerivedData)"),
        (.deviceSupport, "Device Support", "Support files to connect physical devices to Xcode"),
        (.testClones, "Test Clones", "Simulator clones created by Xcode for parallel testing"),
        (.previews, "Previews", "Simulators used by SwiftUI previews"),
        (.archives, "Archives", "App archives (keep the ones you need to symbolicate crashes)")
    ]

    private let androidCategories: [(type: CleanableItemType, title: String, help: String)] = [
        (.androidEmulator, "Emulators", "Android virtual devices (.avd folders)"),
        (.gradleCache, "Gradle", "Gradle build caches and downloaded wrapper distributions"),
        (.androidStudioCache, "Android Studio", "Android Studio IDE caches and indexes"),
        (.androidSdk, "SDK", "SDK platforms (API levels), build tools and system images")
    ]

    private var allCategories: [(type: CleanableItemType, title: String, help: String)] {
        iosCategories + androidCategories
    }

    private var pieSlices: [PieSlice] {
        allCategories.map { category in
            let stats = simulatorManager.categoryStats[category.type]
            let size = stats?.size ?? 0

            return PieSlice(
                value: Double(size),
                color: Theme.Colors.color(for: category.type),
                label: category.title,
                size: ByteCountFormatter.string(fromByteCount: size, countStyle: .file)
            )
        }
    }

    /// Placeholder slices for when data hasn't loaded yet
    private var placeholderSlices: [PieSlice] {
        allCategories.map { category in
            PieSlice(
                value: 1.0,
                color: Theme.Colors.color(for: category.type),
                label: category.title,
                size: "—"
            )
        }
    }

    private var hasData: Bool {
        simulatorManager.totalSize > 0
    }

    var body: some View {
        ZStack {
            ScrollView(showsIndicators: false) {
                VStack(spacing: 0) {
                    // Header
                    VStack(spacing: 6) {
                        Text("Recoverable Space")
                            .font(.system(size: 12, weight: .medium))
                            .foregroundStyle(Theme.Colors.secondaryText)
                            .textCase(.uppercase)
                            .tracking(1.2)

                        if hasData {
                            Text(ByteCountFormatter.string(fromByteCount: simulatorManager.totalSize, countStyle: .file))
                                .font(.system(size: 40, weight: .bold, design: .rounded))
                                .foregroundStyle(Theme.Colors.primaryText)
                                .contentTransition(.numericText(value: Double(simulatorManager.totalSize)))
                        } else {
                            Text("—")
                                .font(.system(size: 40, weight: .bold, design: .rounded))
                                .foregroundStyle(Theme.Colors.secondaryText.opacity(0.4))
                        }
                    }
                    .padding(.top, 36)
                    .padding(.bottom, 28)

                    // Pie Chart — always visible
                    ZStack {
                        PieChart(slices: hasData ? pieSlices : placeholderSlices, size: 180)
                            .opacity(hasData ? 1.0 : 0.25)


                    }
                    .padding(.bottom, 20)
                    .animation(.easeInOut(duration: 0.4), value: hasData)

                    // Legend — iOS rows of 4, then Android
                    VStack(spacing: 8) {
                        ForEach(Array(stride(from: 0, to: iosCategories.count, by: 4)), id: \.self) { start in
                            HStack(spacing: 16) {
                                ForEach(iosCategories[start..<min(start + 4, iosCategories.count)], id: \.type) { category in
                                    let size = simulatorManager.categoryStats[category.type]?.size ?? 0
                                    LegendItem(category: category, size: size, hasData: hasData)
                                }
                            }
                        }
                        HStack(spacing: 16) {
                            ForEach(androidCategories, id: \.type) { category in
                                let size = simulatorManager.categoryStats[category.type]?.size ?? 0
                                LegendItem(category: category, size: size, hasData: hasData)
                            }
                        }
                    }
                    .padding(.bottom, 20)

                    // iOS Section
                    HStack {
                        Text("iOS")
                            .font(.system(size: 11, weight: .bold))
                            .foregroundStyle(Theme.Colors.secondaryText)
                            .textCase(.uppercase)
                            .tracking(0.8)
                        Rectangle()
                            .fill(Theme.Colors.border)
                            .frame(height: 1)
                    }
                    .padding(.horizontal, 32)
                    .padding(.bottom, 12)

                    LazyVGrid(
                        columns: [GridItem(.flexible(), spacing: 16), GridItem(.flexible(), spacing: 16)],
                        spacing: 16
                    ) {
                        ForEach(iosCategories, id: \.type) { category in
                            let stats = simulatorManager.categoryStats[category.type]
                            MinimalCard(
                                title: category.title,
                                type: category.type,
                                size: stats?.size ?? 0,
                                itemCount: stats?.count ?? 0,
                                helpText: category.help,
                                overrideSizeString: hasData ? nil : "—"
                            )
                        }
                    }
                    .padding(.horizontal, 32)
                    .padding(.bottom, 16)

                    // Android Section
                    HStack {
                        Text("Android")
                            .font(.system(size: 11, weight: .bold))
                            .foregroundStyle(Theme.Colors.secondaryText)
                            .textCase(.uppercase)
                            .tracking(0.8)
                        Rectangle()
                            .fill(Theme.Colors.border)
                            .frame(height: 1)
                    }
                    .padding(.horizontal, 32)
                    .padding(.bottom, 12)

                    LazyVGrid(
                        columns: [GridItem(.flexible(), spacing: 16), GridItem(.flexible(), spacing: 16)],
                        spacing: 16
                    ) {
                        ForEach(androidCategories, id: \.type) { category in
                            let stats = simulatorManager.categoryStats[category.type]
                            MinimalCard(
                                title: category.title,
                                type: category.type,
                                size: stats?.size ?? 0,
                                itemCount: stats?.count ?? 0,
                                helpText: category.help,
                                overrideSizeString: hasData ? nil : "—"
                            )
                        }
                    }
                    .padding(.horizontal, 32)
                    .padding(.bottom, 80)
                }
            }
            .opacity(simulatorManager.isScanning || simulatorManager.isCleaning ? 0.3 : 1.0)

            if !(simulatorManager.isScanning || simulatorManager.isCleaning) {
                // Floating Rescan button
                VStack {
                    Spacer()
                    HStack {
                        Spacer()
                        Button(action: {
                            simulatorManager.scan()
                        }) {
                            HStack(spacing: 8) {
                                Image(systemName: "arrow.triangle.2.circlepath")
                                Text("Rescan")
                            }
                            .font(Theme.Fonts.body)
                            .foregroundStyle(Theme.Colors.primaryText)
                            .padding(.horizontal, 24)
                            .padding(.vertical, 12)
                            .background(Color.white.opacity(0.8))
                            .clipShape(Capsule())
                            .overlay(
                                Capsule()
                                    .stroke(Color.white, lineWidth: 1)
                            )
                            .shadow(color: Color.black.opacity(0.1), radius: 10, y: 4)
                        }
                        .buttonStyle(.plain)
                        Spacer()
                    }
                    .padding(.bottom, 20)
                }
            }
        }
        .onChange(of: simulatorManager.isScanning) { _, isScanning in
            if !isScanning {
                showScanComplete = true
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
                    showScanComplete = false
                }
            }
        }
        .onChange(of: simulatorManager.isCleaning) { _, isCleaning in
            if !isCleaning {
                showCleanComplete = true
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
                    showCleanComplete = false
                }
            }
        }
        .onAppear {
            if simulatorManager.items.isEmpty && !simulatorManager.isScanning {
                simulatorManager.scan()
            }
        }
    }
}


private struct LegendItem: View {
    let category: (type: CleanableItemType, title: String, help: String)
    let size: Int64
    let hasData: Bool

    var body: some View {
        HStack(spacing: 6) {
            Circle()
                .fill(Theme.Colors.color(for: category.type))
                .frame(width: 8, height: 8)
            VStack(alignment: .leading, spacing: 0) {
                Text(category.title)
                    .font(.system(size: 10, weight: .medium))
                    .foregroundStyle(Theme.Colors.primaryText)
                Text(hasData ? ByteCountFormatter.string(fromByteCount: size, countStyle: .file) : "—")
                    .font(.system(size: 9, weight: .regular))
                    .foregroundStyle(Theme.Colors.secondaryText)
            }
        }
    }
}

