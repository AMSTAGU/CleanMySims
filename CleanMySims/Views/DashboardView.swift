import SwiftUI

struct DashboardView: View {
    @EnvironmentObject var simulatorManager: SimulatorManager
    @State private var showScanComplete = false
    @State private var showCleanComplete = false

    private let categories: [(type: CleanableItemType, title: String, help: String)] = [
        (.cache, "Caches", "Temporary simulator data: logs, compilation caches, downloaded data"),
        (.virtualDevice, "Simulators", "Virtual iOS devices used by Xcode to test your apps"),
        (.runtimes, "Runtimes", "iOS versions installed to run the simulators"),
        (.builds, "Builds", "Compilation data generated by Xcode (DerivedData)"),
        (.deviceSupport, "Device Support", "Support files to connect physical iPhone/iPad to Xcode")
    ]

    private func sizeForType(_ type: CleanableItemType) -> Int64 {
        simulatorManager.items
            .filter { $0.type == type }
            .reduce(0) { $0 + $1.size }
    }

    private var pieSlices: [PieSlice] {
        categories.map { category in
            let size = sizeForType(category.type)
            return PieSlice(
                value: Double(size),
                color: Theme.Colors.color(for: category.type),
                label: category.title,
                size: ByteCountFormatter.string(fromByteCount: size, countStyle: .file)
            )
        }
    }

    var body: some View {
        ZStack {
            ScrollView {
                VStack(spacing: 0) {
                    // Header
                    VStack(spacing: 4) {
                        Text("Recoverable Space")
                            .font(Theme.Fonts.body)
                            .foregroundStyle(Theme.Colors.secondaryText)

                        Text(ByteCountFormatter.string(fromByteCount: simulatorManager.totalSize, countStyle: .file))
                            .font(Theme.Fonts.title)
                            .foregroundStyle(Theme.Colors.primaryText)
                            .contentTransition(.numericText(value: Double(simulatorManager.totalSize)))
                    }
                    .padding(.top, 40)
                    .padding(.bottom, 24)

                    // Pie Chart
                    if simulatorManager.totalSize > 0 {
                        PieChart(slices: pieSlices, size: 180)
                            .padding(.bottom, 24)

                        // Legend
                        HStack(spacing: 16) {
                            ForEach(categories, id: \.type) { category in
                                HStack(spacing: 4) {
                                    Circle()
                                        .fill(Theme.Colors.color(for: category.type))
                                        .frame(width: 8, height: 8)
                                    Text(category.title)
                                        .font(.system(size: 10))
                                        .foregroundStyle(Theme.Colors.secondaryText)
                                }
                            }
                        }
                        .padding(.bottom, 32)
                    }

                    // Cards Grid
                    LazyVGrid(
                        columns: [
                            GridItem(.flexible(), spacing: 16),
                            GridItem(.flexible(), spacing: 16)
                        ],
                        spacing: 16
                    ) {
                        ForEach(categories, id: \.type) { category in
                            MinimalCard(
                                title: category.title,
                                type: category.type,
                                size: sizeForType(category.type),
                                helpText: category.help
                            )
                        }
                    }
                    .padding(.horizontal, 32)
                    .padding(.bottom, 80) // Space for floating button
                }
            }
            .opacity(simulatorManager.isScanning || simulatorManager.isCleaning ? 0.3 : 1.0)

            if (simulatorManager.isScanning || simulatorManager.isCleaning) {
                // Empty view to occupy space? No, we just hide the button.
                // Or we can keep the spacer.
            } else {
                // Floating Rescan button
                VStack {
                    Spacer()
                    HStack {
                        Spacer()
                        Button(action: {
                            simulatorManager.scan()
                        }) {
                            HStack(spacing: 8) {
                                Image(systemName: "arrow.triangle.2.circlepath")
                                Text("Rescan")
                            }
                            .font(Theme.Fonts.body)
                            .foregroundStyle(Theme.Colors.primaryText)
                            .padding(.horizontal, 24)
                            .padding(.vertical, 12)
                            .background(Color.white.opacity(0.8))
                            .clipShape(Capsule())
                            .overlay(
                                Capsule()
                                    .stroke(Color.white, lineWidth: 1)
                            )
                            .shadow(color: Color.black.opacity(0.1), radius: 10, y: 4)
                        }
                        .buttonStyle(.plain)
                        Spacer()
                    }
                    .padding(.bottom, 24)
                }
            }
        }
        .onChange(of: simulatorManager.isScanning) { _, isScanning in
            if !isScanning {
                // Scan just finished, show completion
                showScanComplete = true
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
                    showScanComplete = false
                }
            }
        }
        .onChange(of: simulatorManager.isCleaning) { _, isCleaning in
            if !isCleaning {
                // Clean just finished, show completion
                showCleanComplete = true
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) {
                    showCleanComplete = false
                }
            }
        }
        .onAppear {
            if simulatorManager.items.isEmpty && !simulatorManager.isScanning {
                simulatorManager.scan()
            }
        }
    }
}



#Preview {
