import SwiftUI

enum NavigationItem: Hashable, Identifiable, CaseIterable {
    case dashboard
    // iOS
    case cache
    case devices
    case runtimes
    case builds
    case deviceSupport
    case testClones
    case previews
    case archives
    // Android
    case androidEmulators
    case gradleCache
    case androidStudioCache
    case androidSdk

    var id: Self { self }

    var label: String {
        switch self {
        case .dashboard: return "Dashboard"
        case .cache: return "Caches"
        case .devices: return "Simulators"
        case .runtimes: return "Runtimes"
        case .builds: return "Builds"
        case .deviceSupport: return "Device Support"
        case .testClones: return "Test Clones"
        case .previews: return "Previews"
        case .archives: return "Archives"
        case .androidEmulators: return "Emulators"
        case .gradleCache: return "Gradle"
        case .androidStudioCache: return "Android Studio"
        case .androidSdk: return "SDK"
        }
    }

    var icon: String {
        switch self {
        case .dashboard: return "gauge.medium"
        case .cache: return "archivebox"
        case .devices: return "iphone"
        case .runtimes: return "gearshape.2"
        case .builds: return "hammer.circle"
        case .deviceSupport: return "iphone.circle"
        case .testClones: return "checkmark.diamond"
        case .previews: return "eye"
        case .archives: return "archivebox.fill"
        case .androidEmulators: return "candybarphone"
        case .gradleCache: return "shippingbox"
        case .androidStudioCache: return "wrench.and.screwdriver"
        case .androidSdk: return "cpu"
        }
    }

    var helpText: String? {
        switch self {
        case .dashboard: return nil
        case .cache: return "Temporary simulator data: logs, compilation caches, downloaded data"
        case .devices: return "Virtual iOS devices used by Xcode to test your apps"
        case .runtimes: return "iOS versions installed to run the simulators"
        case .builds: return "Compilation data generated by Xcode (DerivedData)"
        case .deviceSupport: return "Support files to connect physical devices (iPhone, iPad, Watch, TV, Vision Pro) to Xcode"
        case .testClones: return "Simulator clones created by Xcode for parallel testing (XCTestDevices). Safe to delete"
        case .previews: return "Simulators used by SwiftUI previews. Recreated when needed"
        case .archives: return "App archives from Product > Archive. They hold the dSYMs needed to symbolicate crash reports"
        case .androidEmulators: return "Android virtual devices (.avd folders in ~/.android/avd)"
        case .gradleCache: return "Gradle build caches and downloaded wrapper distributions"
        case .androidStudioCache: return "Android Studio IDE caches and indexes"
        case .androidSdk: return "Android SDK platforms (API levels), build tools and system images"
        }
    }

    var categoryType: CleanableItemType? {
        switch self {
        case .cache: return .cache
        case .devices: return .virtualDevice
        case .runtimes: return .runtimes
        case .builds: return .builds
        case .deviceSupport: return .deviceSupport
        case .testClones: return .testClones
        case .previews: return .previews
        case .archives: return .archives
        case .androidEmulators: return .androidEmulator
        case .gradleCache: return .gradleCache
        case .androidStudioCache: return .androidStudioCache
        case .androidSdk: return .androidSdk
        default: return nil
        }
    }
}

struct SidebarView: View {
    @Binding var selection: NavigationItem?
    @State private var hoveredItem: NavigationItem?
    @Environment(SimulatorManager.self) private var simulatorManager

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            // Header
            HStack(spacing: 10) {
                Image("logo")
                    .resizable()
                    .frame(width: 24, height: 24)
                    .cornerRadius(6)
                Text("CleanMySims")
                    .font(.system(size: 14, weight: .medium))
                    .foregroundStyle(Theme.Colors.primaryText)
            }
            .padding(.horizontal, 16)
            .padding(.vertical, 12)

            // Dashboard
            SidebarItem(
                item: .dashboard,
                selection: $selection,
                hoveredItem: $hoveredItem
            )
            .disabled(simulatorManager.isScanning || simulatorManager.isCleaning)
            .opacity(simulatorManager.isScanning || simulatorManager.isCleaning ? 0.5 : 1.0)
            
            // Spacer/Padding between Dashboard and Categories
            Spacer().frame(height: 10)

            // iOS Section
            Text("iOS")
                .font(.system(size: 10, weight: .semibold))
                .foregroundStyle(Theme.Colors.secondaryText.opacity(0.55))
                .textCase(.uppercase)
                .tracking(0.8)
                .padding(.horizontal, 20)
                .padding(.bottom, 2)

            ForEach([NavigationItem.builds, .cache, .devices, .testClones, .previews, .runtimes, .deviceSupport, .archives], id: \.self) { item in
                SidebarItem(
                    item: item,
                    selection: $selection,
                    hoveredItem: $hoveredItem
                )
                .disabled(simulatorManager.isScanning || simulatorManager.isCleaning)
                .opacity(simulatorManager.isScanning || simulatorManager.isCleaning ? 0.5 : 1.0)
            }

            Spacer().frame(height: 8)

            // Android Section
            Text("Android")
                .font(.system(size: 10, weight: .semibold))
                .foregroundStyle(Theme.Colors.secondaryText.opacity(0.55))
                .textCase(.uppercase)
                .tracking(0.8)
                .padding(.horizontal, 20)
                .padding(.bottom, 2)

            ForEach([NavigationItem.androidEmulators, .gradleCache, .androidStudioCache, .androidSdk], id: \.self) { item in
                SidebarItem(
                    item: item,
                    selection: $selection,
                    hoveredItem: $hoveredItem
                )
                .disabled(simulatorManager.isScanning || simulatorManager.isCleaning)
                .opacity(simulatorManager.isScanning || simulatorManager.isCleaning ? 0.5 : 1.0)
            }

            Spacer()
            
            // Footer
            VStack(spacing: 8) {
                // Links
                HStack(spacing: 12) {
                    Link(destination: URL(string: "https://github.com/AMSTAGU/CleanMySims")!) {
                        Image("github")
                            .resizable()
                            .renderingMode(.template)
                            .frame(width: 20, height: 20)
                            .foregroundStyle(Theme.Colors.secondaryText)
                    }
                    .buttonStyle(.plain)
                    .help("View on GitHub")

                    Link(destination: URL(string: "https://buymeacoffee.com/amstagu")!) {
                        Image("coffee")
                            .resizable()
                            .renderingMode(.template)
                            .frame(width: 20, height: 20)
                            .foregroundStyle(Theme.Colors.secondaryText)
                    }
                    .buttonStyle(.plain)
                    .help("Buy me a coffee")
                }

                // Version
                if let version = Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String {
                    Text("v\(version)")
                        .font(.system(size: 10))
                        .foregroundStyle(Theme.Colors.secondaryText.opacity(0.6))
                }
            }
            .frame(maxWidth: .infinity)
            .padding(.bottom, 16)
        }
    }
}

struct SidebarItem: View {
    let item: NavigationItem
    @Binding var selection: NavigationItem?
    @Binding var hoveredItem: NavigationItem?
    @State private var isHelpHovered = false

    private var isSelected: Bool {
        selection == item
    }

    private var isHovered: Bool {
        hoveredItem == item && !isSelected
    }

    private var accentColor: Color {
        if let type = item.categoryType {
            return Theme.Colors.color(for: type)
        }
        return Theme.Colors.primaryText
    }

    var body: some View {
        HStack(spacing: 12) {
            // Icon with colored background
            ZStack {
                RoundedRectangle(cornerRadius: 8) // "Icônes un peu plus arrondies"
                    .fill(
                        LinearGradient(
                            colors: [
                                accentColor, // Darker/Vibrant base
                                accentColor.opacity(0.5) // Lighter/Translucent top
                            ],
                            startPoint: .bottomTrailing,
                            endPoint: .topLeading
                        )
                    )
                    // Optional: subtle shadow on the shape itself to make it pop slightly
                    .shadow(color: Color.black.opacity(0.1), radius: 2, x: 0, y: 1)

                Image(systemName: item.icon)
                    .font(.system(size: 12, weight: .semibold))
                    .foregroundStyle(.white)
                    // "Petite ombre derrière l'icône" (Small shadow behind the icon)
                    .shadow(color: Color.black.opacity(0.2), radius: 1, x: 0, y: 1)
            }
            .frame(width: 24, height: 24)

            Text(item.label)
                .font(Theme.Fonts.body)
                .foregroundStyle(Theme.Colors.primaryText) // Always primary text for readability
                .fontWeight(isSelected ? .medium : .regular)

            Spacer()

            if let helpText = item.helpText {
                HelpIcon(tooltip: helpText)
            }
        }
        .padding(.horizontal, 16)
        .padding(.vertical, 4)
        .background(
            ZStack {
                if isSelected {
                    RoundedRectangle(cornerRadius: 10)
                        .fill(Color.white.opacity(0.8)) // Less transparent white
                        .shadow(color: Color.black.opacity(0.05), radius: 2, x: 0, y: 1)
                }
            }
            .padding(.horizontal, 8) // "Espace sur le bord" but background fills the rest
        )
        .contentShape(Rectangle())
        .onTapGesture {
            selection = item
        }
        .onHover { hovering in
            hoveredItem = hovering ? item : nil
        }
    }
}

